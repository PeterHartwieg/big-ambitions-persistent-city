using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.RegularExpressions;

namespace PersistentCity.Tests;

public sealed record FoundComment(int Line, string Text);

public static class CommentBanScanner
{
    public const string Message = "comment ban: fix the problem or open an issue";

    public static readonly string[] Categories =
        { "workaround", "known-gap", "todo", "temporary", "skipped", "imperfect-choice", "runtime-doc" };

    static readonly Regex Directive = new Regex(@"^(#\s*(type:|noqa|pragma|shellcheck|fmt:)|//\s*<auto-generated)", RegexOptions.CultureInvariant);
    static readonly Regex Coding = new Regex(@"^#.*coding[:=]", RegexOptions.CultureInvariant);
    static readonly Regex Region = new Regex(@"^#\s*(region|endregion)\b", RegexOptions.CultureInvariant);
    static readonly Regex Space = new Regex(@"\s+", RegexOptions.CultureInvariant);

    public static bool Scanned(string path)
    {
        string name = path.Substring(path.LastIndexOf('/') + 1);
        if (name == ".gitignore" || name == ".gitattributes") return true;
        int dot = name.LastIndexOf('.');
        if (dot < 0) return false;
        switch (name.Substring(dot))
        {
            case ".cs": case ".py": case ".sh": case ".css": case ".html": case ".xml":
            case ".csproj": case ".props": case ".targets":
                return true;
            default:
                return false;
        }
    }

    public static string Collapse(string text) => Space.Replace(text, " ").Trim();

    public static List<FoundComment> Scan(string path, string text)
    {
        var spans = new List<(int Start, int End)>();
        string name = path.Substring(path.LastIndexOf('/') + 1);
        if (name.EndsWith(".cs", StringComparison.Ordinal)) new CSharpLexer(text, spans).Run();
        else if (name.EndsWith(".py", StringComparison.Ordinal)) new PythonLexer(text, spans).Run();
        else if (name.EndsWith(".sh", StringComparison.Ordinal)) Hash(text, spans, true);
        else if (name == ".gitignore" || name == ".gitattributes") Hash(text, spans, false);
        else if (name.EndsWith(".css", StringComparison.Ordinal)) Css(text, spans);
        else Markup(text, spans);
        var found = new List<FoundComment>();
        foreach (var (start, end) in spans)
        {
            string raw = text.Substring(start, end - start);
            int line = 1;
            for (int i = 0; i < start; i++) if (text[i] == '\n') line++;
            if (start == 0 && raw.StartsWith("#!", StringComparison.Ordinal)) continue;
            if (Directive.IsMatch(raw)) continue;
            if (line <= 2 && name.EndsWith(".py", StringComparison.Ordinal) && Coding.IsMatch(raw)) continue;
            found.Add(new FoundComment(line, Collapse(raw)));
        }
        return found;
    }

    public static List<string> Check(IEnumerable<(string Path, string Text)> files, IEnumerable<string> allowlist)
    {
        var failures = new List<string>();
        var allowed = new Dictionary<(string, string), bool>();
        int number = 0;
        foreach (string entry in allowlist)
        {
            number++;
            if (entry.Length == 0) continue;
            string[] parts = entry.Split('\t');
            if (parts.Length != 3 || !Categories.Contains(parts[1]) || parts[2].Length == 0 || Collapse(parts[2]) != parts[2])
            {
                failures.Add($"comment-excuses.txt:{number}: malformed line");
                continue;
            }
            allowed[(parts[0], parts[2])] = false;
        }
        foreach (var (path, text) in files)
        {
            if (!Scanned(path)) continue;
            foreach (var comment in Scan(path, text))
            {
                if (allowed.ContainsKey((path, comment.Text))) allowed[(path, comment.Text)] = true;
                else failures.Add($"{path}:{comment.Line}: {Message}");
            }
        }
        foreach (var pair in allowed.Where(p => !p.Value))
            failures.Add($"comment-excuses.txt: stale excuse, no such comment in {pair.Key.Item1}: {pair.Key.Item2}");
        return failures;
    }

    static void Hash(string s, List<(int, int)> spans, bool shell)
    {
        int n = s.Length;
        bool lineStart = true;
        for (int i = 0; i < n; i++)
        {
            char c = s[i];
            if (c == '\n') { lineStart = true; continue; }
            if (shell && (c == '"' || c == '\''))
            {
                int j = i + 1;
                while (j < n && s[j] != c) j += c == '"' && s[j] == '\\' ? 2 : 1;
                i = j;
                lineStart = false;
                continue;
            }
            if (c == '#' && (lineStart || (shell && (s[i - 1] == ' ' || s[i - 1] == '\t' || s[i - 1] == ';'))))
            {
                int k = s.IndexOf('\n', i);
                if (k < 0) k = n;
                spans.Add((i, k));
                i = k - 1;
                continue;
            }
            if (c != ' ' && c != '\t') lineStart = false;
        }
    }

    static void Css(string s, List<(int, int)> spans)
    {
        int n = s.Length;
        for (int i = 0; i < n; i++)
        {
            char c = s[i];
            if (c == '"' || c == '\'')
            {
                int j = i + 1;
                while (j < n && s[j] != c && s[j] != '\n') j += s[j] == '\\' ? 2 : 1;
                i = j;
                continue;
            }
            if (c == '/' && i + 1 < n && s[i + 1] == '*')
            {
                int k = s.IndexOf("*/", i + 2, StringComparison.Ordinal);
                k = k < 0 ? n : k + 2;
                spans.Add((i, k));
                i = k - 1;
            }
        }
    }

    static void Markup(string s, List<(int, int)> spans)
    {
        int i = 0;
        while (true)
        {
            int j = s.IndexOf("<!--", i, StringComparison.Ordinal);
            if (j < 0) return;
            int k = s.IndexOf("-->", j + 4, StringComparison.Ordinal);
            k = k < 0 ? s.Length : k + 3;
            spans.Add((j, k));
            i = k;
        }
    }

    sealed class CSharpLexer
    {
        readonly string s;
        readonly List<(int, int)> spans;
        int i;

        public CSharpLexer(string text, List<(int, int)> found) { s = text; spans = found; }

        public void Run() => Code(false);

        void Code(bool inner)
        {
            int n = s.Length, depth = 0;
            bool lineStart = true;
            while (i < n)
            {
                char c = s[i];
                if (!inner && lineStart)
                {
                    int j = i;
                    while (j < n && (s[j] == ' ' || s[j] == '\t')) j++;
                    if (j < n && s[j] == '#')
                    {
                        int k = s.IndexOf('\n', j);
                        if (k < 0) k = n;
                        string line = s.Substring(j, k - j);
                        if (Region.IsMatch(line)) spans.Add((j, k));
                        else
                        {
                            int m = line.IndexOf("//", StringComparison.Ordinal);
                            if (m >= 0) spans.Add((j + m, k));
                        }
                        i = k;
                        continue;
                    }
                    lineStart = false;
                }
                if (c == '\n') { lineStart = true; i++; continue; }
                if (c == '/' && i + 1 < n && s[i + 1] == '/')
                {
                    int k = s.IndexOf('\n', i);
                    if (k < 0) k = n;
                    spans.Add((i, k));
                    i = k;
                    continue;
                }
                if (c == '/' && i + 1 < n && s[i + 1] == '*')
                {
                    int k = s.IndexOf("*/", i + 2, StringComparison.Ordinal);
                    k = k < 0 ? n : k + 2;
                    spans.Add((i, k));
                    i = k;
                    continue;
                }
                if (c == '"') { i++; Str(false, false); continue; }
                if (c == '@' || c == '$')
                {
                    int j = i;
                    bool verbatim = false, interpolated = false;
                    while (j < n && (s[j] == '@' || s[j] == '$'))
                    {
                        verbatim |= s[j] == '@';
                        interpolated |= s[j] == '$';
                        j++;
                    }
                    if (j < n && s[j] == '"') { i = j + 1; Str(verbatim, interpolated); continue; }
                    i++;
                    continue;
                }
                if (c == '\'')
                {
                    int j = i + 1;
                    j += j < n && s[j] == '\\' ? 2 : 1;
                    while (j < n && s[j] != '\'' && s[j] != '\n') j++;
                    i = j + 1;
                    continue;
                }
                if (inner)
                {
                    if (c == '{') depth++;
                    else if (c == '}')
                    {
                        if (depth == 0) { i++; return; }
                        depth--;
                    }
                }
                i++;
            }
        }

        void Str(bool verbatim, bool interpolated)
        {
            int n = s.Length;
            while (i < n)
            {
                char c = s[i];
                if (verbatim)
                {
                    if (c == '"')
                    {
                        if (i + 1 < n && s[i + 1] == '"') { i += 2; continue; }
                        i++;
                        return;
                    }
                }
                else
                {
                    if (c == '\\') { i += 2; continue; }
                    if (c == '"' || c == '\n') { i++; return; }
                }
                if (interpolated && c == '{')
                {
                    if (i + 1 < n && s[i + 1] == '{') { i += 2; continue; }
                    i++;
                    Code(true);
                    continue;
                }
                i++;
            }
        }
    }

    sealed class PythonLexer
    {
        readonly string s;
        readonly List<(int, int)> spans;
        int i;

        public PythonLexer(string text, List<(int, int)> found) { s = text; spans = found; }

        public void Run() => Code(false);

        void Code(bool inner)
        {
            int n = s.Length, depth = 0;
            bool statementStart = true, continued = false;
            while (i < n)
            {
                char c = s[i];
                if (c == '\n')
                {
                    if (depth == 0 && !continued) statementStart = true;
                    continued = false;
                    i++;
                    continue;
                }
                if (c == ' ' || c == '\t' || c == '\r' || c == '\f') { i++; continue; }
                if (c == '\\' && i + 1 < n && (s[i + 1] == '\n' || s[i + 1] == '\r')) { continued = true; i++; continue; }
                if (c == '#')
                {
                    int k = s.IndexOf('\n', i);
                    if (k < 0) k = n;
                    spans.Add((i, k));
                    i = k;
                    continue;
                }
                int prefix = PrefixLength(i);
                if (prefix >= 0)
                {
                    int start = i;
                    bool formatted = s.Substring(i, prefix).IndexOfAny(new[] { 'f', 'F' }) >= 0;
                    i += prefix;
                    Str(formatted);
                    if (!inner && depth == 0 && statementStart && RestIsBlank()) spans.Add((start, i));
                    statementStart = false;
                    continue;
                }
                statementStart = false;
                if (c == '(' || c == '[' || c == '{') depth++;
                else if (c == ')' || c == ']' || c == '}')
                {
                    if (inner && c == '}' && depth == 0) { i++; return; }
                    depth--;
                }
                if (char.IsLetterOrDigit(c) || c == '_')
                {
                    while (i < n && (char.IsLetterOrDigit(s[i]) || s[i] == '_')) i++;
                    continue;
                }
                i++;
            }
        }

        bool RestIsBlank()
        {
            int j = i;
            while (j < s.Length && (s[j] == ' ' || s[j] == '\t' || s[j] == '\r')) j++;
            return j >= s.Length || s[j] == '\n' || s[j] == '#' || s[j] == ';';
        }

        int PrefixLength(int at)
        {
            int j = at;
            while (j < s.Length && j - at < 2 && "rRbBuUfF".IndexOf(s[j]) >= 0) j++;
            if (j < s.Length && (s[j] == '"' || s[j] == '\'')) return j - at;
            return -1;
        }

        void Str(bool formatted)
        {
            int n = s.Length;
            char quote = s[i];
            bool triple = i + 2 < n && s[i + 1] == quote && s[i + 2] == quote;
            i += triple ? 3 : 1;
            while (i < n)
            {
                char c = s[i];
                if (c == '\\') { i += 2; continue; }
                if (triple)
                {
                    if (c == quote && i + 2 < n && s[i + 1] == quote && s[i + 2] == quote) { i += 3; return; }
                }
                else if (c == quote || c == '\n') { i++; return; }
                if (formatted && c == '{')
                {
                    if (i + 1 < n && s[i + 1] == '{') { i += 2; continue; }
                    i++;
                    Code(true);
                    continue;
                }
                i++;
            }
        }
    }
}
