using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using Xunit;

namespace PersistentCity.Tests;

public sealed class CommentBanTests
{
    [Fact]
    public void TheTreeHasOnlyListedExcusesAndDirectives()
    {
        string root = Root();
        var files = TrackedFiles(root)
            .Where(CommentBanScanner.Scanned)
            .Where(p => File.Exists(Path.Combine(root, p)))
            .Select(p => (p, File.ReadAllText(Path.Combine(root, p))));
        var failures = CommentBanScanner.Check(files, File.ReadAllLines(Path.Combine(root, "comment-excuses.txt")));
        Assert.True(failures.Count == 0, string.Join(Environment.NewLine, failures));
    }

    [Fact]
    public void APlainCommentFailsWithItsLine()
    {
        var failures = CommentBanScanner.Check(new[] { ("Core/A.cs", "class A\n{\n    int x; // the count\n}\n") }, Array.Empty<string>());
        Assert.Equal(new[] { "Core/A.cs:3: " + CommentBanScanner.Message }, failures);
    }

    [Fact]
    public void AListedExcusePasses()
    {
        var files = new[] { ("Core/A.cs", "class A\n{\n    //   TODO: drop   the\tfallback\n}\n") };
        Assert.Empty(CommentBanScanner.Check(files, new[] { "Core/A.cs\ttodo\t// TODO: drop the fallback" }));
        Assert.Single(CommentBanScanner.Check(files, new[] { "Core/B.cs\ttodo\t// TODO: drop the fallback" }), f => f.StartsWith("Core/A.cs:3:", StringComparison.Ordinal));
    }

    [Fact]
    public void AStaleOrMalformedExcuseFails()
    {
        var files = new[] { ("Core/A.cs", "class A { }\n") };
        Assert.Single(CommentBanScanner.Check(files, new[] { "Core/A.cs\ttodo\t// gone" }));
        Assert.Single(CommentBanScanner.Check(files, new[] { "Core/A.cs\tnote\t// gone" }));
    }

    [Fact]
    public void DirectivesPass()
    {
        string cs = "#nullable enable\n#pragma warning disable CS0168\n#if DEBUG\nclass A { }\n#endif\n// <auto-generated/>\n";
        Assert.Empty(CommentBanScanner.Scan("Core/A.cs", cs));
        Assert.Empty(CommentBanScanner.Scan("tools/a.py", "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nx = 1  # noqa: E501\n"));
        Assert.Empty(CommentBanScanner.Scan("tools/a.sh", "#!/bin/sh\n# shellcheck disable=SC2086\necho $# ${#x}\n"));
        Assert.Single(CommentBanScanner.Scan("Core/A.cs", "#region Parts\nclass A { }\n"));
    }

    [Fact]
    public void StringContentsAreNotComments()
    {
        string cs = "var a = \"http://x/*y*/\"; var b = @\"c:\\\\\"\"//\"; var c = $\"{(d ? \"//\" : \"#\")}//{{\"; var e = '/'; var f = '\\'';\n";
        Assert.Empty(CommentBanScanner.Scan("Core/A.cs", cs));
        string py = "a = 'x # y'\nb = f\"{c['#']} # d\"\nr = r'\\'#'\nfn(\"\"\"#\nnot a docstring\"\"\")\n";
        Assert.Empty(CommentBanScanner.Scan("tools/a.py", py));
        Assert.Empty(CommentBanScanner.Scan("tools/a.sh", "echo \"a # b\" 'c # d' x#y\n"));
        Assert.Empty(CommentBanScanner.Scan("a.css", ".a { content: \"/* no */\"; }\n"));
    }

    [Fact]
    public void EachLanguageCommentIsFound()
    {
        Assert.Equal(new[] { 1, 2, 3 }, CommentBanScanner.Scan("Core/A.cs", "/// <summary>x</summary>\n/* a\n*/ int x; /* b */\n").Select(c => c.Line));
        Assert.Equal(new[] { "\"\"\"Module.\"\"\"", "# note", "'''Doc.'''" },
            CommentBanScanner.Scan("tools/a.py", "\"\"\"Module.\"\"\"\nx = 1  # note\ndef f():\n    '''Doc.'''\n    return x\n").Select(c => c.Text));
        Assert.Single(CommentBanScanner.Scan("tools/a.sh", "echo hi # note\n"));
        Assert.Single(CommentBanScanner.Scan("a.csproj", "<Project>\n  <!-- note -->\n</Project>\n"));
        Assert.Single(CommentBanScanner.Scan(".gitignore", "# note\nbin/\n"));
        Assert.Single(CommentBanScanner.Scan("a.css", "/* note */\n.a { }\n"));
    }

    [Fact]
    public void PythonFormatSpecsAreStringText()
    {
        Assert.Empty(CommentBanScanner.Scan("tools/a.py", "x = f\"{value:#06x}\"\ny = f\"{v:{w}#x} {d['k']!r:#>{n}}\"\n"));
        Assert.Single(CommentBanScanner.Scan("tools/a.py", "x = f\"{value:#06x}\"  # note\n"));
    }

    [Fact]
    public void ASingleLineSuiteDocstringIsFound()
    {
        Assert.Equal(new[] { "\"\"\"Describe f.\"\"\"", "'C.'", "\"\"\"G.\"\"\"" },
            CommentBanScanner.Scan("tools/a.py", "def f(): \"\"\"Describe f.\"\"\"\nclass C(B): 'C.'\nasync def g(a: int = 1) -> \"T\": \"\"\"G.\"\"\"\n").Select(c => c.Text));
        Assert.Empty(CommentBanScanner.Scan("tools/a.py", "def f(): return \"x\"\nh = lambda: \"y\"\nz: \"T\" = \"w\"\nfn(a, \"b\")\n"));
    }

    [Fact]
    public void ShellHeredocsAreTextAndSubstitutionsAreCode()
    {
        Assert.Empty(CommentBanScanner.Scan("tools/a.sh", "cat <<'EOF'\n# literal output\nEOF\ncat <<-EOF > x\n\t# also literal\n\tEOF\nx=$(( 1 << 2 )); y=<<<\"# z\"\n"));
        Assert.Equal(new[] { 1, 6 },
            CommentBanScanner.Scan("tools/a.sh", "echo \"$(date # explanation\n)\"\ncat <<EOF\nbody\nEOF\necho done # after\n").Select(c => c.Line));
    }

    static IEnumerable<string> TrackedFiles(string root)
    {
        var start = new ProcessStartInfo("git", "ls-files -z")
        {
            WorkingDirectory = root,
            RedirectStandardOutput = true,
            UseShellExecute = false,
        };
        using var git = Process.Start(start)!;
        string output = git.StandardOutput.ReadToEnd();
        git.WaitForExit();
        Assert.Equal(0, git.ExitCode);
        return output.Split('\0', StringSplitOptions.RemoveEmptyEntries);
    }

    static string Root()
    {
        var root = new DirectoryInfo(AppContext.BaseDirectory);
        while (root != null && !File.Exists(Path.Combine(root.FullName, "comment-excuses.txt"))) root = root.Parent;
        Assert.NotNull(root);
        return root!.FullName;
    }
}
